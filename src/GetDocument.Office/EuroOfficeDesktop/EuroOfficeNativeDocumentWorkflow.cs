namespace GetDocument.Office.EuroOfficeDesktop;

/// <summary>
/// Conservative status exposed to the GET shell: a CEF view callback is not
/// evidence of OOXML parsing, a saved revision or an exported/validated PDF.
/// </summary>
public enum EuroOfficeNativeDocumentStatus
{
    Requested,
    ViewLoadedUnverified,
    Closed,
    Failed
}

public sealed record EuroOfficeNativeEvent(string Name, int Code, string SessionId);

/// <summary>
/// GD-31J.7 offline experimental coordinator. No native host is attached.
/// Tracks only allowlisted SDK events; never grants "saved", "printed",
/// "document opened" or WORM writeback on the basis of an event alone.
///
/// Status is intentionally immutable beyond "unverified" until future
/// trusted CAS, OOXML validation and GET print-wizard adapters are available.
/// </summary>
public sealed class EuroOfficeNativeDocumentWorkflow
{
    private static readonly IReadOnlyDictionary<string, int> AllowedEvents =
        new Dictionary<string, int>(StringComparer.Ordinal)
        {
            // Synthetic event generated by our QCefView subclass, not a
            // CEF application-manager event code and NOT import confirmation.
            ["view-loaded"] = 10,
            ["modified"] = 1012,
            ["on-save"] = 3002,
            ["print-end"] = 5013,
            ["closed"] = 2001
        };

    private readonly object _sync = new();
    private readonly string _sessionId;
    private bool _modified;
    private bool _saveNotification;
    private bool _printNotification;
    private bool _revisionIntentCreated;
    private bool _pdfIntentCreated;
    private EuroOfficeNativeDocumentStatus _status;

    public string DocumentId { get; }
    public EuroOfficeNativeDocumentWorkflow(string documentId, string sessionId)
    {
        if (string.IsNullOrWhiteSpace(documentId) || documentId.Length > 128 ||
            string.IsNullOrWhiteSpace(sessionId) || sessionId.Length > 128)
            throw new ArgumentException("Нужны идентификаторы документа и лабораторного сеанса.");
        DocumentId = documentId;
        _sessionId = sessionId;
        _status = EuroOfficeNativeDocumentStatus.Requested;
    }

    public EuroOfficeNativeDocumentStatus Status { get { lock (_sync) return _status; } }
    public bool ModifiedNotificationObserved { get { lock (_sync) return _modified; } }
    public bool SaveNotificationObserved { get { lock (_sync) return _saveNotification; } }
    public bool PrintNotificationObserved { get { lock (_sync) return _printNotification; } }

    // No native callback is enough to satisfy the full trusted acceptance
    // conditions. These are deliberately false without a separate adapter.
    public bool DocumentVerified => false;
    public bool SaveCompleted => false;
    public bool PdfReady => false;
    public bool PrintApproved => false;

    public void Observe(EuroOfficeNativeEvent message)
    {
        ArgumentNullException.ThrowIfNull(message);
        lock (_sync)
        {
            if (message.SessionId != _sessionId ||
                !AllowedEvents.TryGetValue(message.Name, out int code) ||
                code != message.Code)
                throw new InvalidDataException("Чужое или неподтверждённое событие EuroOffice.");
            EnsureOpen();
            switch (message.Name)
            {
                case "view-loaded":
                    _status = EuroOfficeNativeDocumentStatus.ViewLoadedUnverified;
                    break;
                case "modified":
                    _modified = true; // only a notification; no verified diff
                    break;
                case "on-save":
                    _saveNotification = true; // not a trusted save receipt
                    break;
                case "print-end":
                    _printNotification = true; // no validated PDF/printer
                    break;
                case "closed":
                    _status = EuroOfficeNativeDocumentStatus.Closed;
                    break;
            }
        }
    }

    /// <summary>
    /// Import a diagnostic receipt from a host process that the caller has
    /// already associated with this session. The native JSON itself is not
    /// authenticated and cannot authorize any document or print operation.
    /// </summary>
    public void ApplyNativeReceipt(EuroOfficeNativeReceipt receipt, string sessionId)
    {
        ArgumentNullException.ThrowIfNull(receipt);
        lock (_sync)
        {
            if (sessionId != _sessionId)
                throw new InvalidDataException("Отчёт принадлежит другому сеансу.");
            EnsureOpen();
            if (receipt.ViewLoaded)
                _status = EuroOfficeNativeDocumentStatus.ViewLoadedUnverified;
            _modified |= receipt.ModifiedNotificationObserved;
            _saveNotification |= receipt.SaveNotificationObserved;
            _printNotification |= receipt.PrintNotificationObserved;
        }
    }

    public string CreateRevisionIntent(string stagedRoot, string source, string destination,
        bool editableWorkingCopy)
    {
        lock (_sync)
        {
            EnsureOpen();
            if (!editableWorkingCopy)
                throw new InvalidOperationException("WORM и неподтверждённые рабочие копии запрещены.");
            if (_revisionIntentCreated)
                throw new InvalidOperationException("Запрос новой редакции уже сформирован.");
            // Uses GD-31J's bounded local staging path validation. It does NOT
            // modify files, commit CAS, or turn native OnSave into confirmation.
            string command = EuroOfficeDesktopProbeProtocol.CreateSaveRequest(
                stagedRoot, source, destination, wormOriginal: false);
            _revisionIntentCreated = true;
            return command;
        }
    }

    public string CreatePdfIntent(string stagedRoot, string source, string destination)
    {
        lock (_sync)
        {
            EnsureOpen();
            if (_pdfIntentCreated)
                throw new InvalidOperationException("Запрос экспорта PDF уже сформирован.");
            string command = EuroOfficeDesktopProbeProtocol.CreateExportPdfRequest(
                stagedRoot, source, destination);
            _pdfIntentCreated = true;
            return command;
        }
    }

    public void AuthorizeDirectPrint() =>
        throw new NotSupportedException("Печать выполняется только через мастер печати ГЭТ.");

    public void Fail(string reason)
    {
        if (string.IsNullOrWhiteSpace(reason) || reason.Length > 256)
            throw new ArgumentException("Не указан код ошибки лабораторного редактора.");
        lock (_sync)
        {
            EnsureOpen();
            _status = EuroOfficeNativeDocumentStatus.Failed;
        }
    }

    private void EnsureOpen()
    {
        if (_status is EuroOfficeNativeDocumentStatus.Failed or EuroOfficeNativeDocumentStatus.Closed)
            throw new InvalidOperationException("Лабораторный сеанс закрыт или завершился ошибкой.");
    }
}
